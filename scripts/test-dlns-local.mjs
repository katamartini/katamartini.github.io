import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {indexedDB}=require('../.cache/dlns-tools/node_modules/fake-indexeddb');
const model=require('../dlns/model.js');
const create=require('../dlns/local-store.js');
const snapshot=JSON.parse(fs.readFileSync(new URL('../dlns/history.json',import.meta.url)));
const store=create(model,indexedDB), other=create(model,indexedDB);
assert.equal((await store.read()).version,0);
let data=await store.importData(snapshot,'repository snapshot',0);
assert.equal(data.matches.length,363);
assert.equal(data.matches.flatMap(m=>m.actions).length,5808);
assert.deepEqual(data.matches,snapshot.matches);
assert.equal((await other.read()).version,1);
await assert.rejects(store.importData(snapshot,'stale',0),/Workspace changed/);
let match=structuredClone(data.matches[0]);match.winner=match.winner==='left'?'right':'left';
data=await store.saveMatch(match,match.revision,match.match_id,1);
assert.equal(data.matches.find(m=>m.match_id===match.match_id).revision,2);
assert.equal(data.changes.at(-1).before.revision,1);
await assert.rejects(other.saveMatch(match,1,match.match_id,1),/Workspace changed/);
await assert.rejects(other.saveMatch(match,1,match.match_id,2),/changed/);
await assert.rejects(store.saveMatch(match,null,null,2),/exists/);
const invalid=structuredClone(snapshot);invalid.matches[0].actions=[];
await assert.rejects(store.importData(invalid,'invalid',2),/Complete all/);
assert.equal((await store.read()).version,2);
const duplicate=structuredClone(snapshot);duplicate.matches.push(duplicate.matches[0]);
assert.throws(()=>store.validate(duplicate),/Duplicate match/);
const historical=snapshot.matches.find(m=>m.match_id==='44-NA-F-1');
await assert.rejects(store.saveMatch(historical,1,historical.match_id,2),/two heroes/);
data=await store.addTeam('Local team','EU',2);assert.equal(data.teams.length,1);
const backup=structuredClone(data);
data=await store.importData(backup,'backup round trip',3);
assert.deepEqual(data.matches,backup.matches);assert.deepEqual(data.teams,backup.teams);
assert.deepEqual(data.changes.at(-1).importedBackup,backup);
data=await store.importData({at:123,matches:snapshot.matches,teams:[{name:'Cached team',region:'NA'}]},'original cache',4);
assert.equal(data.provenance.cache_at,123);assert.equal(data.teams[0].name,'Cached team');
await assert.rejects(create(model,null).read(),/unavailable/);
console.log('PASS local store: full snapshot preservation, cache/backup imports, historical anomalies, atomic invalid imports, conflicts, team registration and unavailable storage.');
