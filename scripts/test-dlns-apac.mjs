import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),m=require('../dlns/model.js');
const validate=require('../dlns/local-store.js')(m,null).validate;
const game=(week,region,round='Challenger',game=1,winner='left',played_on='')=>{
  const match={week,region,round,game,winner,left_team:region+' A',right_team:region+' B',first_pick:'left',
    actions:m.sequence('left',week,region).map((action,i)=>({...action,hero:m.heroes[i],player:''}))};
  return {...match,match_id:m.matchId(match),...(played_on?{played_on}:{})};
};
const completed=(week,region)=>[game(week,region),game(week,region,'Finals'),game(week,region,'Finals',2)];
const ids=['63-NA-F-2','1-APAC-C-1','1-APAC-F-1','1-APAC-F-2','64-EU-C-1'];
assert.deepEqual(ids.slice().reverse().sort((a,b)=>m.chronology(a)-m.chronology(b)),ids);
assert.equal(m.timelineWeek(game(1,'APAC')),63);
assert.equal(m.timelineWeek(game(3,'APAC')),65);
assert.equal(m.timelineWeek(game(5,'APAC','Challenger',1,'left','2026-12-11')),68);
assert.ok(m.chronology(game(1,'APAC','Challenger',1,'left','2026-11-14'))>m.chronology('64-EU-C-1'),'an entered date overrides the schedule');
const naDone=completed(63,'NA'),euDone=completed(63,'EU'),ap=game(1,'APAC'),f1=game(1,'APAC','Finals');
const f2=game(1,'APAC','Finals',2,'right'),f3=game(1,'APAC','Finals',3);
const id=(matches,region)=>m.matchId(m.nextOpenMatch(matches,region));
assert.equal(id([...euDone,...naDone]),'1-APAC-C-1');
assert.equal(id([...euDone,...naDone.slice(0,2),ap]),'63-NA-F-2');
assert.equal(id([...euDone,...naDone,ap,f1]),'1-APAC-F-2');
assert.equal(id([...euDone,...naDone,ap,f1,f2]),'1-APAC-F-3');
assert.equal(id([...euDone,...naDone,ap,f1,f2,f3]),'64-EU-C-1');
assert.equal(id([...euDone,...naDone],'EU'),'64-EU-C-1');
assert.equal(id([...euDone,...naDone,game(64,'EU')],'APAC'),'1-APAC-C-1');
assert.deepEqual(m.gameOneTeams([euDone[1],ap,f1,f2],f3),{left:'APAC A',right:'APAC B'});
assert.equal(m.gameOneTeams([euDone[1],ap],f3),null);
assert.equal(m.banCount(1,'APAC'),3);
assert.equal(m.banCount(1,'EU'),2);
assert.equal(m.matchToSim(ap).slots.left.bans.length,3);
assert.equal(m.withFirstPick(m.matchToSim(ap),'right').events.length,18);
assert.deepEqual(m.validateMatch(ap),[]);
const future=game(5,'APAC','Challenger',1,'left','2026-12-11');
assert.equal(m.simToMatch(m.matchToSim(future),future).played_on,'2026-12-11');
assert.equal(m.matchToRecords(future)[0].played_on,'2026-12-11');
assert.match(m.validateMatch({...future,played_on:''}).join(' '),/date this APAC match/);
assert.match(m.validateMatch({...future,played_on:'2026-02-31'}).join(' '),/valid match date/);
assert.equal(validate({matches:[future],teams:[{name:'APAC A',region:'APAC'}]}).matches[0].played_on,'2026-12-11');
console.log('DLNS APAC: official match IDs, play-date ordering, known schedule progression, manual region override, Game 1 sides, 3-ban drafts and date-preserving storage passed.');
